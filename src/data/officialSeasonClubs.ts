// Clean team name helper
function cleanName(raw: string): string {
  if (!raw) return '';
  return raw
    .toLowerCase()
    .replace(/^(สโมสรฟุตบอล|สโมสร|ทีมฟุตบอล|ทีม)\s*/g, '')
    .replace(/\s*(เอฟซี|fc|ยูไนเต็ด|utd|united|ซิตี้|city|สเตเดียม|stadium|ฟุตบอลคลับ)\s*$/gi, '')
    .replace(/[.\-_()/\\]/g, ' ')
    .replace(/\s+/g, '')
    .trim();
}

/**
 * Find canonical official club by name matching
 */
export function getCanonicalOfficialClub(
  inputName?: string, 
  leagueHint?: LeagueType
): { name: string; league: LeagueType } | null {
  if (!inputName || !inputName.trim()) return null;
  const raw = inputName.trim();

  // 0. Check alias dictionary
  if (CLUB_ALIASES[raw]) {
    const aliased = CLUB_ALIASES[raw];
    for (const [league, list] of Object.entries(OFFICIAL_CLUBS_BY_LEAGUE) as [LeagueType, readonly string[]][]) {
      if (list.includes(aliased)) {
        return { name: aliased, league };
      }
    }
  }

  const cIn = cleanName(raw);

  // Check alias on cleaned name
  for (const [aliasKey, target] of Object.entries(CLUB_ALIASES)) {
    if (cleanName(aliasKey) === cIn) {
      for (const [league, list] of Object.entries(OFFICIAL_CLUBS_BY_LEAGUE) as [LeagueType, readonly string[]][]) {
        if (list.includes(target)) {
          return { name: target, league };
        }
      }
    }
  }

  // 1. Direct exact match in hint league
  if (leagueHint) {
    const directInHint = OFFICIAL_CLUBS_BY_LEAGUE[leagueHint].find(
      c => c === raw || cleanName(c) === cIn
    );
    if (directInHint) {
      return { name: directInHint, league: leagueHint };
    }
  }

  // 2. Direct exact match across all leagues
  for (const [league, list] of Object.entries(OFFICIAL_CLUBS_BY_LEAGUE) as [LeagueType, readonly string[]][]) {
    const found = list.find(c => c === raw || cleanName(c) === cIn);
    if (found) {
      return { name: found, league };
    }
  }

  // 3. Substring / contains match with prioritization
  // Check in hint league first
  if (leagueHint) {
    const subInHint = OFFICIAL_CLUBS_BY_LEAGUE[leagueHint].find(c => {
      const cTarget = cleanName(c);
      return cTarget.length >= 3 && (cIn.includes(cTarget) || cTarget.includes(cIn));
    });
    if (subInHint) {
      return { name: subInHint, league: leagueHint };
    }
  }

  // Check across all leagues
  for (const [league, list] of Object.entries(OFFICIAL_CLUBS_BY_LEAGUE) as [LeagueType, readonly string[]][]) {
    const found = list.find(c => {
      const cTarget = cleanName(c);
      return cTarget.length >= 3 && (cIn.includes(cTarget) || cTarget.includes(cIn));
    });
    if (found) {
      return { name: found, league };
    }
  }

  return null;
}

/**
 * Check whether a club name is recognized as an official season club
 */
export function isOfficialSeasonClub(inputName?: string): boolean {
  return getCanonicalOfficialClub(inputName) !== null;
}
